/**
 * Calculates ministry performance score based on minister competency and budget allocation
 */
export function computeMinistryPerformance(ministry: Ministry, minister: Minister): number {
  const comp = minister.attributes.competency;
  const lead = minister.attributes.leadership;
  const baseScore = comp * 0.6 + lead * 0.4;
  return Math.max(20, Math.min(100, Math.round(baseScore)));
}
